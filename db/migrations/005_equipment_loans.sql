CREATE TABLE IF NOT EXISTS equipment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, category TEXT NOT NULL, quantity INT NOT NULL CHECK(quantity > 0),
 damaged_quantity INT NOT NULL DEFAULT 0 CHECK(damaged_quantity >= 0 AND damaged_quantity <= quantity)
);
CREATE TABLE IF NOT EXISTS equipment_loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 equipment_id BIGINT NOT NULL REFERENCES equipment(id),
 user_id UUID NOT NULL REFERENCES profiles(id), quantity INT NOT NULL CHECK(quantity > 0),
 checked_out_by UUID NOT NULL REFERENCES profiles(id), checked_in_by UUID REFERENCES profiles(id),
 borrowed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), due_at TIMESTAMPTZ NOT NULL,
 returned_at TIMESTAMPTZ, condition TEXT CHECK(condition IN ('good','damaged')),
 damaged_quantity INT NOT NULL DEFAULT 0 CHECK(damaged_quantity >= 0 AND damaged_quantity <= quantity),
 notes TEXT, CHECK(due_at > borrowed_at), CHECK(returned_at IS NULL OR returned_at >= borrowed_at)
);
CREATE INDEX IF NOT EXISTS equipment_loans_active ON equipment_loans(equipment_id) WHERE returned_at IS NULL;
