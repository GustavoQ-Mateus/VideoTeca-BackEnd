-- ── Pedido de equipamento feito por aluno ou professor ───────────────
CREATE TABLE IF NOT EXISTS equipment_requests (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  equipment_id BIGINT NOT NULL REFERENCES equipment(id),
  quantity     INT NOT NULL CHECK (quantity BETWEEN 1 AND 50),
  pickup_at    TIMESTAMPTZ NOT NULL,
  return_at    TIMESTAMPTZ NOT NULL,
  purpose      TEXT NOT NULL,
  notes        TEXT,
  status       TEXT NOT NULL DEFAULT 'analysis',
  staff_notes  TEXT,
  decided_by   UUID REFERENCES profiles(id),
  decided_at   TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (return_at > pickup_at),
  CHECK (status IN ('analysis', 'approved', 'refused', 'cancelled'))
);
CREATE INDEX IF NOT EXISTS idx_equipment_requests_user ON equipment_requests (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_equipment_requests_status ON equipment_requests (status, created_at);

-- ── Sugestões de título para a programação ───────────────────────────
CREATE TABLE IF NOT EXISTS film_suggestions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  title       TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  year        INT CHECK (year IS NULL OR year BETWEEN 1880 AND 2100),
  director    TEXT,
  project     TEXT NOT NULL CHECK (project IN ('bibcine', 'vai_de_serie')),
  reason      TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 2000),
  status      TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'approved', 'rejected')),
  staff_notes TEXT,
  decided_at  TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_film_suggestions_status ON film_suggestions (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_film_suggestions_title ON film_suggestions (lower(title));

-- ── Atendimento (SAC) ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS contact_tickets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  topic      TEXT NOT NULL CHECK (char_length(topic) BETWEEN 1 AND 80),
  reference  TEXT,
  status     TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'answered', 'closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS contact_messages (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  BIGINT NOT NULL REFERENCES contact_tickets(id) ON DELETE CASCADE,
  author_id  UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  from_staff BOOLEAN NOT NULL DEFAULT FALSE,
  body       TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_contact_tickets_user ON contact_tickets (user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_contact_tickets_status ON contact_tickets (status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_contact_messages_ticket ON contact_messages (ticket_id, created_at);
